    static func packId(for premiumCategory: String) -> String? {
        switch premiumCategory {
        case "Sinema": return "sinema"
        case "Bilim+": return "bilim"
        case "Tarih+": return "tarih_plus"
        case "Spor+":  return "spor_yildizlari"
